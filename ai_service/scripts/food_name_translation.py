def translate_food_name(name: str) -> str:
    name_lower = name.lower().strip()
    
    if name_lower in FOOD_NAME_MAPPING:
        return FOOD_NAME_MAPPING[name_lower]
    
    words = name_lower.split()
    translated_words = []
    for word in words:
        if word in FOOD_NAME_MAPPING:
            translated_words.append(FOOD_NAME_MAPPING[word])
        else:
            translated_words.append(word)
    
    result = "".join(translated_words)
    
    if result == name_lower:
        return name
    return result

def translate_category(category: str) -> str:
    if not category:
        return "其他"
    
    for en, zh in CATEGORY_MAPPING_EN_ZH.items():
        if en in category.lower():
            return zh
    
    return "其他"